#include "user.h"
#include "VariablesInit.h"
#include "FOCLevel.h"

/*==============================================================================
                        BUILDLEVEL 配置表

  下标即 BUILDLEVEL 的取值。字段含义见 FOCLevel.h 中 LEVEL_CFG 的注释。

  分级遵循调试/起动的自然推进顺序，每一级只引入一个新环节：
    L1  离线测硬件 —— 纯台架，验证 PWM 端口与基础计算（不接主电路）
    L2  VF 开环    —— 虚拟角度 + 开环电压矢量，验证 ADC 采样与坐标变换
    L3  IF 控制    —— 固定 Iq 电流 + 斜坡转频率让电机开环起转；同时读 QEP
                      验证编码器信号，但控制角度仍用虚拟角（读而不用）
    L4  QEP 闭环   —— 用编码器真实角度做速度/电流双闭环测性能
    L5  保留       —— 空置（等同 L0 保护态），留给后续其他控制算法

  编码器(QEP)从 L3 就开始读取（用于编码器故障检测），但只有 L4 才把它的
  角度真正接入控制环。L1/L2 不依赖位置反馈。
==============================================================================*/
static const LEVEL_CFG LevelCfg[] =
{
    /* L0 关闭 PWM 输出（保护态），所有环节都不启用 */
    { 0U, 0U, LSWMODE_STOP,   0U, 0U, 0U, 0U },

    /* L1 SVPWM 开环输出，！！！不接主电路、不接电机！！！
         只在台架上验证 PWM 端口与基础计算，因此不采样、不用编码器、忽略 lsw */
    { 0U, 0U, LSWMODE_IGNORE, 0U, 0U, 0U, 0U },

    /* L2 VF 开环控制（虚拟角度），验证 AD 采样与坐标变换
         电流采样但不开环，角度用虚拟角度发生器 */
    { 1U, 0U, LSWMODE_STOP,   0U, 0U, 0U, 0U },

    /* L3 IF 控制（电流-频率开环起动），验证电流环 PI
         注入固定 Iq 给定、用斜坡发生器转频率/角度，让电机开环起转。
         QEP 此时被读取、用来做编码器故障检测（角度跳变/Z 丢失/超速），
         但控制角度仍走虚拟角（AngleFromQep = 0，即"读而不用"）。
         lsw=0 抱轴对齐到电气零位，lsw=1 转频起动 */
    { 1U, 1U, LSWMODE_LOCK,   0U, 1U, 0U, 0U },

    /* L4 速度闭环（QEP 真实角度）
         lsw=0 抱轴标定，lsw=1 电流环（虚拟角），lsw>=2 速度环（真实角） */
    { 1U, 1U, LSWMODE_LOCK,   1U, 1U, 1U, 1U },

    /* L5 保留（等同 L0 保护态，占空比压 0），留给后续其他控制算法 */
    { 0U, 0U, LSWMODE_STOP,   0U, 0U, 0U, 0U },
};

#define LEVEL_CFG_COUNT  (sizeof(LevelCfg) / sizeof(LevelCfg[0]))

/*------------------------------------------------------------------------------
  本拍生效的配置行（声明见 FOCLevel.h）

  上电初值指向 L0（保护态），这样在第一次 Level_Apply() 之前
  流水线读到的是"什么都不做"的配置，不会误动作。
------------------------------------------------------------------------------*/
const LEVEL_CFG *cfg = &LevelCfg[0];

/*------------------------------------------------------------------------------
  依据 BUILDLEVEL 刷新 cfg
------------------------------------------------------------------------------*/
void Level_Apply(void)
{
    Uint32 level = BUILDLEVEL;

    /* 越界的 BUILDLEVEL（例如手误写成 4、6）一律落到 L0 保护态。
       若不这样处理，所有分支都不进，PWM 比较值会冻结在最后一次的值上，
       电机会以最后占空比继续运行，而中断照常应答，从外部看不出异常。 */
    if (level >= LEVEL_CFG_COUNT)
    {
        level = 0U;
    }

    cfg = &LevelCfg[level];
}
